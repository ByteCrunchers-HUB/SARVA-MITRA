import os
import sys
from pathlib import Path
from dotenv import load_dotenv

load_dotenv()

# Add project root to sys.path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

from backend.rag_pipeline.rag import RAGPipeline, compact_chat_history

def test_multiturn():
    print("Initializing RAGPipeline...")
    rag = RAGPipeline()
    
    print(f"Master Prompt Length: {len(rag.master_prompt)} chars (~{len(rag.master_prompt)//4} tokens)")
    assert len(rag.master_prompt) < 7000, f"Master prompt should be trimmed Part B, got {len(rag.master_prompt)}"

    readings = {
        "temperature_c": 23.6,
        "humidity_pct": 90.0,
        "soil_moisture_pct": 16.1,
        "rainfall_mm": 0.0,
        "sunlight_wm2": 0.0,
        "risk_pct": 85.0,
        "risk_level": "high",
    }
    ml_prediction = {
        "risk_percentage": 85.0,
        "risk_level": "high",
        "anomaly_flag": 1,
    }

    # Turn 1
    q1 = "How can I prevent flower drop and yellowing leaves under these conditions?"
    print("\n--- Turn 1: User asks:", q1)
    ans1, struct1 = rag.answer(
        readings=readings,
        ml_output=1,
        crop="Tomato",
        location="Vijayawada",
        question=q1,
        chat_history=[],
        ml_prediction=ml_prediction,
    )
    print("Turn 1 Answer snippet:", ans1[:200], "...")
    assert len(ans1) > 50

    # Build history
    history = [
        {"role": "user", "content": q1},
        {"role": "assistant", "content": ans1},
    ]

    compacted = compact_chat_history(history)
    print("\nCompacted History preview:\n", compacted)
    assert len(compacted) < 600, f"Compacted history too long: {len(compacted)}"

    # Turn 2: User asks follow-up
    q2 = "Should I reduce irrigation or apply calcium nitrate first?"
    print("\n--- Turn 2: User asks:", q2)
    ans2, struct2 = rag.answer(
        readings=readings,
        ml_output=1,
        crop="Tomato",
        location="Vijayawada",
        question=q2,
        chat_history=history,
        ml_prediction=ml_prediction,
        k_recent_turns=1,
    )
    print("Turn 2 Answer snippet:", ans2[:200], "...")
    assert len(ans2) > 20

    # Turn 3: User asks about conversation history (history now has 4 messages > buffer of 2, triggering LLM summarization)
    history.append({"role": "user", "content": q2})
    history.append({"role": "assistant", "content": ans2})

    q3 = "whats the history of this chat summarize what q i have asked so far"
    print("\n--- Turn 3: User asks:", q3)
    ans3, struct3 = rag.answer(
        readings=readings,
        ml_output=1,
        crop="Tomato",
        location="Vijayawada",
        question=q3,
        chat_history=history,
        ml_prediction=ml_prediction,
        k_recent_turns=1,
    )
    print(f"\n🧠 Running Summary generated by LLM:\n{rag.last_summary}")
    assert len(rag.last_summary) > 10, "Summary should be populated by LLM"
    print("\nTurn 3 Answer:\n", ans3)
    assert len(ans3) > 20
    print("\n✅ Multi-turn chat with progressive LLM summarization PASSED without 413 rate limit error!")

if __name__ == "__main__":
    test_multiturn()
